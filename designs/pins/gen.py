# Generate the pin designs of phase 5 (README (p)): combinational designs
# whose only job is to use DE25-Nano pins, so the image shows each pin's
# input or output configuration and nothing clocked.
#
#   python3 -I designs/pins/gen.py <out dir>     writes <out>/{pt,ph1,ph2}
#
# pt  fits the pin template: a few pins per bank, both directions, both
#     HVIO voltages, two IO96 lanes.
# ph1, ph2 hold out every other DE25-Nano pin; ph1 has the even pins of
#     de25_pins.tsv as outputs and the odd ones as inputs, ph2 the reverse,
#     so between them every held-out pin is used both ways.
# Each output is the XOR of two inputs, so nothing folds to a constant.
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
pins = []
for line in open(os.path.join(here, 'de25_pins.tsv')):
    if line.startswith('#') or line.startswith('signal\t'):
        continue
    sig, ball, std, bank, block, pad = line.rstrip('\n').split('\t')
    pins.append((sig, ball, std, bank, block, pad))
by_sig = {p[0]: p for p in pins}

# Training pins: out and in, one or more per HVIO bank, IO96 lanes 4 and 5.
TRAIN_OUT = ['LED[0]', 'LED[2]', 'LED[5]', 'GPIO1_D[1]', 'HDMI_TX_D[12]', 'GPIO0_D[7]', 'DRAM_ADDR[7]']
TRAIN_IN = ['SW[0]', 'SW[2]', 'FAN_ALERT_n', 'GPIO1_D[23]', 'GPIO0_D[31]', 'HDMI_TX_D[5]', 'DRAM_DQ[0]']


def std_of(p):
    # DPHY pins are used single-ended at the bank's 1.1 V: the D-PHY
    # standard itself is not covered (README (p)).
    return '1.1-V' if p[2] == 'DPHY' else p[2]


def port(sig):
    return 'p_' + sig.replace('[', '_').replace(']', '')


def write(name, outs, ins, outdir):
    d = os.path.join(outdir, name)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, name + '.qpf'), 'w') as f:
        f.write(f'PROJECT_REVISION = "{name}"\n')
    with open(os.path.join(d, name + '.sdc'), 'w') as f:
        f.write('')
    q = [
        'set_global_assignment -name FAMILY "Agilex 5"',
        'set_global_assignment -name DEVICE A5EB013BB23BE4SCS',
        f'set_global_assignment -name TOP_LEVEL_ENTITY {name}',
        f'set_global_assignment -name VERILOG_FILE {name}.v',
        f'set_global_assignment -name SDC_FILE {name}.sdc',
        'set_global_assignment -name DEVICE_INITIALIZATION_CLOCK OSC_CLK_1_125MHZ',
        'set_global_assignment -name PROJECT_OUTPUT_DIRECTORY output_files',
        'set_global_assignment -name PWRMGT_VOLTAGE_OUTPUT_FORMAT "LINEAR FORMAT"',
        'set_global_assignment -name PWRMGT_LINEAR_FORMAT_N "-12"',
        'set_global_assignment -name NUM_PARALLEL_PROCESSORS 2',
        '',
    ]
    for s in outs + ins:
        p = by_sig[s]
        q.append(f'set_location_assignment PIN_{p[1]} -to {port(s)}')
        q.append(f'set_instance_assignment -name IO_STANDARD "{std_of(p)}" -to {port(s)}')
    with open(os.path.join(d, name + '.qsf'), 'w') as f:
        f.write('\n'.join(q) + '\n')
    v = [f'// Generated by designs/pins/gen.py: {len(outs)} outputs, {len(ins)} inputs.',
         f'module {name} (']
    decl = [f'    input  wire {port(s)}' for s in ins] + [f'    output wire {port(s)}' for s in outs]
    v.append(',\n'.join(decl))
    v.append(');')
    n = len(ins)
    for i, s in enumerate(outs):
        a, b = ins[i % n], ins[(i * 7 + 3) % n]
        if a == b:
            b = ins[(i + 1) % n]
        v.append(f'    assign {port(s)} = {port(a)} ^ {port(b)};')
    v.append('endmodule')
    with open(os.path.join(d, name + '.v'), 'w') as f:
        f.write('\n'.join(v) + '\n')


def main():
    outdir = sys.argv[1]
    write('pt', TRAIN_OUT, TRAIN_IN, outdir)
    rest = [p[0] for p in pins if p[0] not in TRAIN_OUT + TRAIN_IN]
    even, odd = rest[0::2], rest[1::2]
    write('ph1', even, odd, outdir)
    write('ph2', odd, even, outdir)


if __name__ == '__main__':
    main()
