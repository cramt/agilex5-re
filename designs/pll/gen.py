# IOPLL designs for README (v): four IOPLLs per design, one in each of the
# DE25-Nano's hviowr blocks, each fed by its bank's PLL reference pin, with
# different reference and output frequencies. Every output clocks an 8-bit
# counter whose top bit drives an HVIO pin; each PLL's locked drives one too.
# pa is the training design, pb the held-out one.
#   python3 -I designs/pll/gen.py      (writes designs/pa and designs/pb)
import os

here = os.path.dirname(os.path.abspath(__file__))
STD = {'3.3': '3.3-V LVCMOS', '1.8': '1.8-V LVCMOS'}
# (ref ball, standard, ref MHz, [out MHz], [out balls], locked ball)
DESIGNS = {
    'pa': [('CE19', '3.3', 50, [75, 30], ['BV11', 'BV16'], 'BV19'),
           ('V16', '3.3', 50, [120], ['AE19'], 'AG31'),
           ('BF23', '3.3', 50, [33.333333, 200], ['AT11', 'AT14'], 'AT19'),
           ('AE11', '1.8', 25, [125], ['AE14'], 'AE6')],
    'pb': [('CE19', '3.3', 50, [64, 160], ['BV11', 'BV16'], 'BV19'),
           ('V16', '3.3', 50, [100, 12.5], ['AE19', 'AH16'], 'AG31'),
           ('BF23', '3.3', 50, [270], ['AT11'], 'AT19'),
           ('AE11', '1.8', 25, [40, 80], ['AE14', 'AE8'], 'AE6')],
}
for name, plls in DESIGNS.items():
    d = os.path.join(os.path.dirname(here), name)
    os.makedirs(d, exist_ok=True)
    ports = [f'    input  wire r{i},' for i in range(len(plls))]
    outs = []
    body = []
    qsf = [f'set_global_assignment -name FAMILY "Agilex 5"', 'set_global_assignment -name DEVICE A5EB013BB23BE4SCS',
           f'set_global_assignment -name TOP_LEVEL_ENTITY {name}', f'set_global_assignment -name VERILOG_FILE {name}.v',
           f'set_global_assignment -name SDC_FILE {name}.sdc', 'set_global_assignment -name DEVICE_INITIALIZATION_CLOCK OSC_CLK_1_125MHZ',
           'set_global_assignment -name PROJECT_OUTPUT_DIRECTORY output_files', 'set_global_assignment -name PWRMGT_VOLTAGE_OUTPUT_FORMAT "LINEAR FORMAT"',
           'set_global_assignment -name PWRMGT_LINEAR_FORMAT_N "-12"', 'set_global_assignment -name NUM_PARALLEL_PROCESSORS 2', '']
    sdc = []
    prep = ['# Generate the four IOPLL IPs (README (v)) into the run directory.',
            'set root [file normalize [file join $::quartus(binpath) .. ..]]',
            'set ipd [file join $root qsys bin ip-deploy]', 'set qg [file join $root qsys bin qsys-generate]']
    for i, (ref, std, fref, fouts, balls, lock) in enumerate(plls):
        qsf.append(f'set_location_assignment PIN_{ref} -to r{i}')
        qsf.append(f'set_instance_assignment -name IO_STANDARD "{STD[std]}" -to r{i}')
        qsf.append(f'set_global_assignment -name IP_FILE pll{i}.ip')
        sdc.append(f'create_clock -name r{i} -period {1000 / fref:.4f} [get_ports r{i}]')
        params = [f'--component-parameter=gui_reference_clock_frequency={fref}', f'--component-parameter=gui_number_of_clocks={len(fouts)}']
        params += [f'--component-parameter=gui_output_clock_frequency{k}={f}' for k, f in enumerate(fouts)]
        prep.append(f'if {{[catch {{exec $ipd --component-name=altera_iopll --output-name=pll{i} --family=Agilex\\ 5 --part=A5EB013BB23BE4SCS '
                    f'{" ".join(params)} --component-parameter=gui_use_locked=true 2>@1}} r]}} {{ puts "ip-deploy failed: $r"; exit 1 }}')
        prep.append(f'if {{[catch {{exec $qg pll{i}.ip --synthesis=VERILOG --family=Agilex\\ 5 --part=A5EB013BB23BE4SCS 2>@1}} r]}} '
                    '{ puts "qsys-generate failed: [string range $r end-2000 end]"; exit 1 }')
        conns = ', '.join(f'.outclk_{k}(c{i}_{k})' for k in range(len(fouts)))
        body.append(f'    wire {", ".join(f"c{i}_{k}" for k in range(len(fouts)))};')
        body.append(f'    pll{i} u{i} (.refclk(r{i}), .rst(1\'b0), {conns}, .locked(l{i}));')
        outs.append(f'    output wire l{i},')
        qsf.append(f'set_location_assignment PIN_{lock} -to l{i}')
        qsf.append(f'set_instance_assignment -name IO_STANDARD "{STD[std]}" -to l{i}')
        for k, b in enumerate(balls):
            body.append(f'    reg [7:0] n{i}_{k} = 0; always @(posedge c{i}_{k}) n{i}_{k} <= n{i}_{k} + 1\'b1; assign o{i}_{k} = n{i}_{k}[7];')
            outs.append(f'    output wire o{i}_{k},')
            qsf.append(f'set_location_assignment PIN_{b} -to o{i}_{k}')
            qsf.append(f'set_instance_assignment -name IO_STANDARD "{STD[std]}" -to o{i}_{k}')
    sdc.append('derive_pll_clocks')
    ports += outs
    ports[-1] = ports[-1].rstrip(',')
    desc = '; '.join(f'PLL{i} {ref} {fref} MHz -> {", ".join(str(f) for f in fouts)} MHz' for i, (ref, _, fref, fouts, _, _) in enumerate(plls))
    v = [f'// IOPLL design {name}, generated by designs/pll/gen.py (README (v)): {desc}.', f'module {name} (', *ports, ');', *body, 'endmodule']
    open(os.path.join(d, f'{name}.v'), 'w').write('\n'.join(v) + '\n')
    open(os.path.join(d, f'{name}.qsf'), 'w').write('\n'.join(qsf) + '\n')
    open(os.path.join(d, f'{name}.sdc'), 'w').write('\n'.join(sdc) + '\n')
    open(os.path.join(d, f'{name}.qpf'), 'w').write(f'PROJECT_REVISION = "{name}"\n')
    open(os.path.join(d, 'prep.tcl'), 'w').write('\n'.join(prep) + '\n')
