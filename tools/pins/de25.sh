#!/usr/bin/env bash
# Every DE25-Nano user pin as its own pin table (README (p)): the I/O bits
# of a design that uses only that pin, as input and as output, at the
# standard the board's manual gives it (DPHY pins single-ended at 1.1 V).
#   tools/pins/de25.sh > db/sm4revb/io/de25_pins.tsv
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd); repo=$(dirname "$(dirname "$here")")
A=$repo/tools/a5db/target/release/a5db
echo "# Generated by tools/pins/de25.sh from db/sm4revb/io/template.tsv and"
echo "# designs/pins/de25_pins.tsv: one table per (signal, use); apply the rows of"
echo "# one table with a5db apply, or use a5db pins for several pins at once"
echo "# (lane and bank rows are shared, README (p))."
printf "signal\tball\tuse\tuid\tbit\tvalue\n"
grep -v -e '^#' -e '^signal' "$repo/designs/pins/de25_pins.tsv" | while IFS=$'\t' read -r sig ball std bank block pad; do
    case $std in "3.3-V LVCMOS") s=3.3;; "1.8-V LVCMOS") s=1.8;; *) s=1.1;; esac
    for use in in out; do
        "$A" pintable "$repo/db/sm4revb" "$ball=$use:$s" | tail -n +2 | sed "s/^/$sig\t$ball\t$use\t/"
    done
done
